#!/usr/bin/env python3
"""gen.py -- emit the LITERAL / HOLD fit-ladder rungs from r0.v.

r0.v is a byte-for-byte copy of cpld/compositor/compositor.v.  Every other
rung is r0.v with a small set of EXACT textual edits applied here, each of
which must match exactly once, so a rung can never silently drift from the
production source it is priced against.  The emitted rN.v files are what the
fitter and the benches read; nothing reads this script at build time.

  r1   RUN_COLOR removed (src 11 plays as cmp_color0, reserved)
  r2   form A LITERAL: bank held for the literal's slot, then KEEP
  r3   r2 + HOLD(N) (RUN with count bit 11 low -> KEEP for N slots)
  r4   r3 with the run counter narrowed to 10 bits
  r5   form B LITERAL: RGB_OUT loads the colour on the consume edge, then KEEP
  r6   r5 + HOLD(N)
  r6n  r6 with the run counter narrowed to 10 bits
  r5n  form B WITHOUT KEEP (the literal's own slot keeps the previous source)
  r7   streaming RUN on r0 (count bit 11 low: SETs behind it consume while it
       counts), no LITERAL
"""

import pathlib

HERE = pathlib.Path(__file__).parent
R0 = (HERE / "r0.v").read_text()


def edit(src, old, new):
    n = src.count(old)
    if n != 1:
        raise SystemExit(f"edit matched {n} times:\n{old}")
    return src.replace(old, new)


def banner(src, text):
    return f"// LITERAL FIT LADDER RUNG -- {text}\n// Generated by cpld/experiments/literal/gen.py from r0.v; do not edit.\n//\n" + src


# Simulation-only shim: compositor_tb.v probes dut.cur_colour once.  Rungs that
# delete cur_colour expose a constant under LIT_TB so the production bench still
# compiles; the fitter never defines LIT_TB, so the netlist is untouched.
TB_SHIM = """
`ifdef LIT_TB
    wire [2:0] cur_colour = 3'd0;      // sim-only: compositor_tb.v probes it
`endif
"""

# ----------------------------------------------------------------------------
# R1 -- RUN_COLOR removed
# ----------------------------------------------------------------------------

def remove_run_colour(src, src3_name):
    src = edit(src, "    localparam [1:0] SRC_COLOUR      = 2'd3;\n",
               f"    localparam [1:0] {src3_name} = 2'd3;\n")
    src = edit(src, "    reg [2:0]  cur_colour;\n", TB_SHIM)
    src = edit(src,
               "    wire        w_is_colour = w_is_run & (w_src == SRC_COLOUR);\n"
               "    wire [2:0]  w_colour    = staged_word[11:9];\n", "")
    src = edit(src,
               "    // RUN_COLOR's count is nine bits; force the unused top bits to the terminal\n"
               "    // value so one 12-bit comparator serves both encodings.\n"
               "    wire [11:0] w_load = w_is_colour ? {3'b111, staged_word[8:0]} : staged_word[11:0];\n",
               "    wire [11:0] w_load = staged_word[11:0];\n")
    src = edit(src,
               "    wire [11:0] colour_rgb = {{4{cur_colour[2]}}, {4{cur_colour[1]}}, {4{cur_colour[0]}}};\n\n",
               "")
    src = edit(src, "            cur_colour     <= 3'd0;\n", "")
    src = edit(src,
               "                cur_src    <= w_src;\n"
               "                cur_colour <= w_colour;\n",
               "                cur_src    <= w_src;\n")
    return src


r1 = remove_run_colour(R0, "SRC_RESERVED   ")
r1 = edit(r1,
          "        (cur_src == SRC_COLOR0)      ? cmp_color0 :\n"
          "                                       colour_rgb;\n",
          "                                       cmp_color0;   // SRC_RESERVED aliases colour0\n")

# ----------------------------------------------------------------------------
# Shared LITERAL decode: the literal is a RUN with src 11; it loads cur_src
# (= KEEP) like any RUN but does NOT load the counter, which is terminal on its
# consume edge and therefore stays terminal (count_inc's hold term is ~terminal).
# ----------------------------------------------------------------------------

def literal_decode(src, src3="SRC_KEEP"):
    src = edit(src,
               "    wire [11:0] w_value     = staged_word[11:0];\n",
               "    wire [11:0] w_value     = staged_word[11:0];\n"
               f"    wire        w_is_literal = w_is_run & (w_src == {src3});\n")
    src = edit(src,
               "    wire load_run  = consume_active & w_is_run;\n",
               "    wire load_run  = consume_active & w_is_run;\n"
               "    wire load_literal = load_run & w_is_literal;\n"
               "    wire load_count   = load_run & ~w_is_literal;\n")
    src = edit(src,
               "                            load_run  ? w_load  :\n",
               "                            load_count ? w_load  :\n")
    src = edit(src,
               "    wire count_inc = load_run | (H_ACTIVE & ~terminal & ~mask_stall);\n",
               "    wire count_inc = load_count | (H_ACTIVE & ~terminal & ~mask_stall);\n")
    return src


# ----------------------------------------------------------------------------
# R2 -- form A: hold the bank for the literal's slot, mux reads staged_word
# ----------------------------------------------------------------------------

def form_a(src):
    src = remove_run_colour(src, "SRC_KEEP       ")
    src = literal_decode(src)
    src = edit(src,
               "    reg        mask_active;             // a mask record is playing its sixteen slots\n",
               "    reg        mask_active;             // a mask record is playing its sixteen slots\n"
               "    reg        lit_active;              // a literal is showing staged_word this slot\n")
    src = edit(src,
               "    wire buffer_frees = (~have_staged | consume_now) & ~mask_holds;  // free at this edge\n",
               "    wire buffer_frees = (~have_staged | consume_now) & ~mask_holds & ~load_literal;\n")
    src = edit(src,
               "        (cur_src == SRC_COLOR0)      ? cmp_color0 :\n"
               "                                       colour_rgb;\n",
               "        (cur_src == SRC_COLOR0)      ? cmp_color0 :\n"
               "        lit_active                   ? staged_word[11:0] :\n"
               "                                       RGB_OUT;      // SRC_KEEP\n")
    src = edit(src,
               "            mask_active    <= 1'b0;\n",
               "            mask_active    <= 1'b0;\n"
               "            lit_active     <= 1'b0;\n")
    src = edit(src,
               "            mask_active <= mask_next;\n",
               "            mask_active <= mask_next;\n"
               "            lit_active  <= load_literal;\n")
    return src


r2 = form_a(R0)

# ----------------------------------------------------------------------------
# HOLD(N): a non-literal RUN with count bit 11 LOW enters KEEP for N slots.
# cur_src <= w_src | {2{~bit11}} (a literal is src 11 already, so the OR is
# harmless there).  The count loads {2'b11, ~N[9:0]} for a HOLD and the RUN's
# own field otherwise; bit 11 of every run load is therefore the constant 1.
# ----------------------------------------------------------------------------

def hold12(src):
    src = edit(src,
               "    wire [11:0] w_load = staged_word[11:0];\n",
               "    // HOLD (bit 11 low) loads {2'b11, ~N[9:0]}; a RUN has bit 11 high already.\n"
               "    wire [11:0] w_load = {1'b1, staged_word[10] | ~staged_word[11], staged_word[9:0]};\n"
               "    wire [1:0]  w_run_src = w_src | {~staged_word[11], ~staged_word[11]};\n")
    src = edit(src,
               "                cur_src    <= w_src;\n",
               "                cur_src    <= w_run_src;\n")
    return src


def narrow10(src):
    src = edit(src, "    reg [11:0] run_count;               // up-counter, all-ones = expired\n",
               "    reg [9:0]  run_count;               // up-counter, all-ones = expired\n")
    src = edit(src,
               "    // HOLD (bit 11 low) loads {2'b11, ~N[9:0]}; a RUN has bit 11 high already.\n"
               "    wire [11:0] w_load = {1'b1, staged_word[10] | ~staged_word[11], staged_word[9:0]};\n",
               "    wire [9:0]  w_load = staged_word[9:0];   // RUN and HOLD: ~count[9:0]\n")
    src = edit(src, "    wire [11:0] count_mux = load_mask ? 12'hFF0 :\n",
               "    wire [9:0]  count_mux = load_mask ? 10'h3F0 :\n")
    src = edit(src, "            run_count      <= 12'hFFF;\n",
               "            run_count      <= 10'h3FF;\n")
    src = edit(src, "            run_count <= count_mux + {11'd0, count_inc};\n",
               "            run_count <= count_mux + {9'd0, count_inc};\n")
    return src


r3 = hold12(r2)
r4 = narrow10(r3)

# ----------------------------------------------------------------------------
# R5 -- form B: direct load of RGB_OUT on the consume edge, no bank stall
# ----------------------------------------------------------------------------

def form_b(src, keep):
    src = remove_run_colour(src, "SRC_KEEP       ")
    src = literal_decode(src)
    if keep:
        src = edit(src,
                   "        (cur_src == SRC_COLOR0)      ? cmp_color0 :\n"
                   "                                       colour_rgb;\n",
                   "        (cur_src == SRC_COLOR0)      ? cmp_color0 :\n"
                   "                                       RGB_OUT;      // SRC_KEEP\n")
    else:
        # The literal does not touch cur_src; src 11 is never loaded.
        src = edit(src,
                   "        (cur_src == SRC_COLOR0)      ? cmp_color0 :\n"
                   "                                       colour_rgb;\n",
                   "                                       cmp_color0;   // src 11 never loaded\n")
        src = edit(src,
                   "            if (load_run)\n"
                   "            begin\n"
                   "                cur_src    <= w_src;\n",
                   "            if (load_count)\n"
                   "            begin\n"
                   "                cur_src    <= w_src;\n")
    src = edit(src,
               "            RGB_OUT    <= h_active_d ? pixel_mux : 12'h000;\n",
               "            RGB_OUT    <= ~h_active_d  ? 12'h000           :\n"
               "                          load_literal ? staged_word[11:0] :\n"
               "                                         pixel_mux;\n")
    return src


r5 = form_b(R0, keep=True)
r6 = hold12(r5)
r6n = narrow10(r6)
r5n = form_b(R0, keep=False)

# ----------------------------------------------------------------------------
# R7 -- streaming RUN on r0: count bit 11 low flags a RUN during which a staged
# SET is consumed while the count runs.  One flag FF.  RUN_COLOR is excluded
# (its bit 11 is a colour bit).  The RUN's count loads with bit 11 forced high.
# ----------------------------------------------------------------------------

r7 = R0
r7 = edit(r7,
          "    reg        mask_active;             // a mask record is playing its sixteen slots\n",
          "    reg        mask_active;             // a mask record is playing its sixteen slots\n"
          "    reg        streaming;               // the RUN in force lets SETs through\n")
r7 = edit(r7,
          "    wire [11:0] w_load = w_is_colour ? {3'b111, staged_word[8:0]} : staged_word[11:0];\n",
          "    wire [11:0] w_load = {1'b1, w_is_colour ? 2'b11 : staged_word[10:9], staged_word[8:0]};\n"
          "    wire        w_streaming = ~staged_word[11] & ~w_is_colour;\n")
r7 = edit(r7,
          "    wire consume_active = H_ACTIVE & have_staged & terminal;\n",
          "    wire consume_active = H_ACTIVE & have_staged & (terminal | (streaming & w_is_set));\n")
r7 = edit(r7,
          "            mask_active    <= 1'b0;\n",
          "            mask_active    <= 1'b0;\n"
          "            streaming      <= 1'b0;\n")
r7 = edit(r7,
          "                cur_src    <= w_src;\n"
          "                cur_colour <= w_colour;\n",
          "                cur_src    <= w_src;\n"
          "                cur_colour <= w_colour;\n"
          "                streaming  <= w_streaming;\n")

# ----------------------------------------------------------------------------
# R1h -- R1 + HOLD(N) alone (KEEP = RGB_OUT feedback, no literal): prices the
# KEEP feedback by itself.  src 11 RUNs also play as KEEP here.
# ----------------------------------------------------------------------------

r1h = remove_run_colour(R0, "SRC_KEEP       ")
r1h = edit(r1h,
           "        (cur_src == SRC_COLOR0)      ? cmp_color0 :\n"
           "                                       colour_rgb;\n",
           "        (cur_src == SRC_COLOR0)      ? cmp_color0 :\n"
           "                                       RGB_OUT;      // SRC_KEEP\n")
r1h = hold12(r1h)

# ----------------------------------------------------------------------------
# R8 -- form C: a LITERAL is "SET cmp_colorX + select colourX" in one word.
# It writes its colour into a held-colour register on its consume edge and
# loads cur_src with that register's select, so it is an ordinary one-slot
# playback record (L1 intact, banked pairs land on adjacent slots) and the
# RGB_OUT mux gains NO input.  Cost: the register is clobbered.  A flat span
# in any colour is LITERAL + RUN(colourX, N); no HOLD and no KEEP needed.
# ----------------------------------------------------------------------------

def form_c(src, reg):
    sel, tgt = {"cmp_color0": ("SRC_COLOR0", "3'd1"), "cmp_color1": ("SRC_COLOR1", "3'd0")}[reg]
    wname = {"cmp_color0": "write_color0", "cmp_color1": "write_color1"}[reg]
    src = remove_run_colour(src, "SRC_LITERAL    ")
    src = literal_decode(src, "SRC_LITERAL")
    src = edit(src,
               "        (cur_src == SRC_COLOR0)      ? cmp_color0 :\n"
               "                                       colour_rgb;\n",
               "                                       cmp_color0;   // src 11 is never loaded\n")
    src = edit(src,
               f"    wire {wname} = apply_set & (w_target == {tgt});\n",
               f"    wire {wname} = (apply_set & (w_target == {tgt})) | load_literal;\n")
    src = edit(src,
               "                cur_src    <= w_src;\n",
               f"                cur_src    <= w_is_literal ? {sel} : w_src;\n")
    return src


r8 = form_c(R0, "cmp_color0")
r8b = form_c(R0, "cmp_color1")

# R8 ladder continued on the cmp_color1 variant (the one that fits).
r8bh = edit(r8b, "                                       cmp_color0;   // src 11 is never loaded\n",
            "        (cur_src == SRC_COLOR0)      ? cmp_color0 :\n"
            "                                       RGB_OUT;      // KEEP (HOLD only)\n")
r8bh = edit(r8bh, "    wire [11:0] w_load = staged_word[11:0];\n",
            "    // HOLD (bit 11 low) loads {2'b11, ~N[9:0]}; a RUN has bit 11 high already.\n"
            "    wire [11:0] w_load = {1'b1, staged_word[10] | ~staged_word[11], staged_word[9:0]};\n"
            "    wire [1:0]  w_run_src = w_is_literal ? SRC_COLOR1 : (w_src | {~staged_word[11], ~staged_word[11]});\n")
r8bh = edit(r8bh, "                cur_src    <= w_is_literal ? SRC_COLOR1 : w_src;\n",
            "                cur_src    <= w_run_src;\n")
r8bn = edit(r8b, "    wire [11:0] w_load = staged_word[11:0];\n",
            "    // HOLD (bit 11 low) loads {2'b11, ~N[9:0]}; a RUN has bit 11 high already.\n"
            "    wire [11:0] w_load = {1'b1, staged_word[10] | ~staged_word[11], staged_word[9:0]};\n")
r8bn = narrow10(r8bn)

# R9 -- streaming RUN on R8b (count bit 11 low lets staged SETs through).
r9 = r8b
r9 = edit(r9,
          "    reg        mask_active;             // a mask record is playing its sixteen slots\n",
          "    reg        mask_active;             // a mask record is playing its sixteen slots\n"
          "    reg        streaming;               // the RUN in force lets SETs through\n")
r9 = edit(r9, "    wire [11:0] w_load = staged_word[11:0];\n",
          "    wire [11:0] w_load = {1'b1, staged_word[10:0]};\n"
          "    wire        w_streaming = ~staged_word[11] & ~w_is_literal;\n")
r9 = edit(r9,
          "    wire consume_active = H_ACTIVE & have_staged & terminal;\n",
          "    wire consume_active = H_ACTIVE & have_staged & (terminal | (streaming & w_is_set));\n")
r9 = edit(r9,
          "            mask_active    <= 1'b0;\n",
          "            mask_active    <= 1'b0;\n"
          "            streaming      <= 1'b0;\n")
r9 = edit(r9,
          "                cur_src    <= w_is_literal ? SRC_COLOR1 : w_src;\n",
          "                cur_src    <= w_is_literal ? SRC_COLOR1 : w_src;\n"
          "                streaming  <= w_streaming;\n")

# R2s -- form A WITHOUT the bank stall: the literal's slot reads set_pix_value,
# which registers staged_word on every edge and so still holds the literal for
# the one cycle after its consume edge.  Prices the per-bit input alone.
r2s = remove_run_colour(R0, "SRC_KEEP       ")
r2s = literal_decode(r2s)
r2s = edit(r2s,
           "    reg        mask_active;             // a mask record is playing its sixteen slots\n",
           "    reg        mask_active;             // a mask record is playing its sixteen slots\n"
           "    reg        lit_active;              // a literal is showing set_pix_value this slot\n")
r2s = edit(r2s,
           "        (cur_src == SRC_COLOR0)      ? cmp_color0 :\n"
           "                                       colour_rgb;\n",
           "        (cur_src == SRC_COLOR0)      ? cmp_color0 :\n"
           "        lit_active                   ? set_pix_value :\n"
           "                                       RGB_OUT;      // SRC_KEEP\n")
r2s = edit(r2s, "            mask_active    <= 1'b0;\n",
           "            mask_active    <= 1'b0;\n            lit_active     <= 1'b0;\n")
r2s = edit(r2s, "            mask_active <= mask_next;\n",
           "            mask_active <= mask_next;\n            lit_active  <= load_literal;\n")

RUNGS = {
    "r1": (r1, "R1: RUN_COLOR removed, src 11 reserved (plays as cmp_color0)"),
    "r2": (r2, "R2: form A LITERAL (bank held for its slot, then KEEP)"),
    "r3": (r3, "R3: R2 + HOLD(N), 12-bit counter"),
    "r4": (r4, "R4: R3 with a 10-bit run counter"),
    "r5": (r5, "R5: form B LITERAL (direct load on the consume edge, then KEEP)"),
    "r6": (r6, "R6: R5 + HOLD(N), 12-bit counter"),
    "r6n": (r6n, "R6n: R6 with a 10-bit run counter"),
    "r5n": (r5n, "R5n: form B LITERAL without KEEP (own slot keeps previous source)"),
    "r1h": (r1h, "R1h: R1 + HOLD(N) alone (KEEP = RGB_OUT feedback), no literal"),
    "r8": (r8, "R8: form C LITERAL = SET cmp_color0 + select colour0, one word"),
    "r8b": (r8b, "R8b: form C LITERAL into cmp_color1"),
    "r8bh": (r8bh, "R8bh: R8b + HOLD(N) (KEEP = RGB_OUT feedback), 12-bit counter"),
    "r8bn": (r8bn, "R8bn: R8b with a 10-bit run counter (no HOLD)"),
    "r9": (r9, "R9: R8b + streaming RUN (count bit 11 low lets SETs through)"),
    "r2s": (r2s, "R2s: form A colour from set_pix_value, no bank stall"),
    "r7": (r7, "R7: streaming RUN on R0 (bit 11 low lets SETs through), no LITERAL"),
}

for name, (text, what) in RUNGS.items():
    (HERE / f"{name}.v").write_text(banner(text, what))
    print("wrote", name + ".v")
