// psg_tables_gen — writes psg_tables.h, the constant tables the bare-metal
// SN76489 channel driver (psg_channels.*) looks up at run time.
//
// The choices need floating point and a search (for every SN76489 tone
// period, the PERIOD and table LENGTH whose rate is closest in pitch), which a
// 68000 should not do per note and a compiler will not do at compile time
// within its constexpr step limit.  So they are made here, on the host, once,
// and checked in; `make test` regenerates and diffs, so the header can never
// drift from this program.  Host only.
//
// Tables:
//   TONE[N]   N = 1..1024 (index 0 = period register 0 = 1024): PERIOD and
//             LENGTH of a square table, LENGTH 0 = band-limited to silence
//             (fundamental at or above 7,867 Hz: the reference renders it as
//             silence, and so do we)
//   NOISE[R]  R = counter reload 1..1024: PERIOD and REPEAT (each sequence bit
//             deposited REPEAT times) for a shift rate of 3,579,545 / (32 R)
//   VOLUME[a] a = 0..15: VOLUME = round(63 x 10^(-a/10)), 15 -> 0
//   WHITE_BITS  the discrete SN76489AN's 15-bit register (taps 0 and 1, seed
//             0x4000) output bit after 0, 1, 2 ... shifts, 32,767 bits packed
//             LSB first; the periodic sequence is 15 bits, a single 1

#include <cmath>
#include <cstdint>
#include <cstdio>
#include <vector>

namespace
{

constexpr double STEP_HZ = 25175000.0 / 16.0;
constexpr uint32_t PSG_CLOCK_HZ = 3579545;
constexpr int PERIOD_MAX = 255;
constexpr int PREFERRED_MIN_PERIOD = 49;
constexpr int ABSOLUTE_MIN_PERIOD = 12;
constexpr int MAX_TONE_LENGTH = 512;
constexpr double TONE_CENTS_GOAL = 1.0;

bool band_limited(uint32_t n)
{
    const uint64_t numerator = 65536ull * PSG_CLOCK_HZ * 1600;
    const uint64_t denominator = 16ull * 25175000 * n;
    return (numerator + denominator / 2) / denominator >= 0x10000ull;
}

struct Tone
{
    int period = 0;
    int length = 0;
};

Tone choose_tone(uint32_t n)
{
    Tone best{};
    if (band_limited(n))
    {
        return best;
    }
    const double f = static_cast<double>(PSG_CLOCK_HZ) / (32.0 * n);
    double best_error = 1e9;
    auto consider = [&](int period_min)
    {
        for (int p = PERIOD_MAX; p >= period_min; --p)
        {
            const double rate = STEP_HZ / (p + 1);
            const double exact = rate / f;
            const long candidates[2] = { static_cast<long>(std::floor(exact)), static_cast<long>(std::ceil(exact)) };
            for (long l : candidates)
            {
                if (l < 2 || l > MAX_TONE_LENGTH)
                {
                    continue;
                }
                const double err = 1200.0 * std::log2((rate / static_cast<double>(l)) / f);
                if (std::fabs(err) < std::fabs(best_error))
                {
                    best_error = err;
                    best.period = p;
                    best.length = static_cast<int>(l);
                }
            }
        }
    };
    consider(PREFERRED_MIN_PERIOD);
    if (best.length == 0 || std::fabs(best_error) > TONE_CENTS_GOAL)
    {
        consider(ABSOLUTE_MIN_PERIOD);
    }
    return best;
}

struct Noise
{
    int period = 0;
    int repeat = 1;
};

Noise choose_noise(uint32_t reload)
{
    const double shift_hz = static_cast<double>(PSG_CLOCK_HZ) / (32.0 * reload);
    Noise c{};
    double dup = std::ceil(STEP_HZ / (256.0 * shift_hz));
    if (dup < 1.0)
    {
        dup = 1.0;
    }
    c.repeat = static_cast<int>(dup);
    long p = std::lround(STEP_HZ / (c.repeat * shift_hz)) - 1;
    if (p < ABSOLUTE_MIN_PERIOD)
    {
        p = ABSOLUTE_MIN_PERIOD;
    }
    if (p > PERIOD_MAX)
    {
        p = PERIOD_MAX;
    }
    c.period = static_cast<int>(p);
    return c;
}

int volume(int a)
{
    return (a >= 15) ? 0 : static_cast<int>(std::lround(63.0 * std::pow(10.0, -0.1 * a)));
}

}   // namespace

int main()
{
    printf("// psg_tables.h -- GENERATED by psg_tables_gen.cpp (`make -C audio tables`).\n"
           "// Do not edit; `make -C audio test` regenerates and diffs it.\n\n"
           "#pragma once\n\n#include <cstdint>\n\nnamespace griffin::audio::psg_tables\n{\n\n");

    printf("struct ToneEntry\n{\n    uint8_t  period;\n    uint16_t length;     // 0 = band-limited: silent\n};\n\n");
    printf("// Indexed by the raw 10-bit period register (0 means 1024).\n");
    printf("inline constexpr ToneEntry TONE[1024] =\n{\n");
    for (uint32_t r = 0; r < 1024; ++r)
    {
        const Tone t = choose_tone(r ? r : 1024);
        printf("    { %3d, %3d },%s", t.period, t.length, (r % 4 == 3) ? "\n" : "");
    }
    printf("};\n\n");

    printf("struct NoiseEntry\n{\n    uint8_t  period;\n    uint8_t  repeat;\n};\n\n");
    printf("// Indexed by the noise counter reload, 1..1024 (index 0 unused).\n");
    printf("inline constexpr NoiseEntry NOISE[1025] =\n{\n    { 0, 1 },\n");
    for (uint32_t r = 1; r <= 1024; ++r)
    {
        const Noise n = choose_noise(r);
        printf("    { %3d, %2d },%s", n.period, n.repeat, (r % 4 == 0) ? "\n" : "");
    }
    printf("};\n\n");

    printf("inline constexpr uint8_t VOLUME[16] = {");
    for (int a = 0; a < 16; ++a)
    {
        printf(" %d%s", volume(a), a < 15 ? "," : " ");
    }
    printf("};\n\n");

    std::vector<uint8_t> bits;
    uint16_t reg = 0x4000;
    do
    {
        bits.push_back(static_cast<uint8_t>(reg & 1));
        const uint16_t feedback = static_cast<uint16_t>((reg ^ (reg >> 1)) & 1);
        reg = static_cast<uint16_t>(reg >> 1);
        if (feedback)
        {
            reg = static_cast<uint16_t>(reg | 0x4000);
        }
    } while (reg != 0x4000);
    printf("inline constexpr uint32_t WHITE_LENGTH = %zu;\n", bits.size());
    printf("inline constexpr uint32_t PERIODIC_LENGTH = 15;\n\n");
    printf("// Bit i of the white sequence is WHITE_BITS[i / 8] >> (i %% 8) & 1.\n");
    printf("inline constexpr uint8_t WHITE_BITS[%zu] =\n{", (bits.size() + 7) / 8);
    for (size_t i = 0; i < (bits.size() + 7) / 8; ++i)
    {
        uint8_t b = 0;
        for (int k = 0; k < 8; ++k)
        {
            const size_t j = i * 8 + static_cast<size_t>(k);
            if (j < bits.size() && bits[j])
            {
                b = static_cast<uint8_t>(b | (1u << k));
            }
        }
        printf("%s0x%02X,", (i % 16 == 0) ? "\n    " : " ", b);
    }
    printf("\n};\n\n}   // namespace griffin::audio::psg_tables\n");
    return 0;
}
